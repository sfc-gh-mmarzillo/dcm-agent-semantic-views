-- One-time bootstrap (run as ACCOUNTADMIN). A DCM project cannot define its own parent
-- database/schema, so those containers, the deployer role, and the project objects live here.
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS DCM_DEMO;
CREATE SCHEMA IF NOT EXISTS DCM_DEMO.PROJECTS;

-- Deployer role: used by humans for DEV and by CI for DEV + PROD
CREATE ROLE IF NOT EXISTS DCM_DEPLOYER;
GRANT ROLE DCM_DEPLOYER TO ROLE SYSADMIN;
GRANT ROLE DCM_DEPLOYER TO USER MMARZILLO;

GRANT USAGE, CREATE SCHEMA ON DATABASE DCM_DEMO TO ROLE DCM_DEPLOYER;
GRANT USAGE, CREATE DCM PROJECT, CREATE STAGE ON SCHEMA DCM_DEMO.PROJECTS TO ROLE DCM_DEPLOYER;
GRANT USAGE ON WAREHOUSE AICOLLEGE TO ROLE DCM_DEPLOYER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE DCM_DEPLOYER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE DCM_DEPLOYER;   -- required by agent evaluations

-- Remove the single-env project from the first iteration (never deployed)
DROP DCM PROJECT IF EXISTS DCM_DEMO.PROJECTS.AGENT_SV_DEMO;

-- One DCM project per environment, owned by the deployer role
USE ROLE DCM_DEPLOYER;
CREATE DCM PROJECT IF NOT EXISTS DCM_DEMO.PROJECTS.AGENT_SV_DEMO_DEV;
CREATE DCM PROJECT IF NOT EXISTS DCM_DEMO.PROJECTS.AGENT_SV_DEMO_PROD;
